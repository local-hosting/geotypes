#!/usr/bin/env node --import tsx
/** Regenerate place-archetype config + geotype layout meta from YAML sources. */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

import {
  assertPlaceArchetype,
  type PlaceArchetypeConfig,
} from '../src/resolve-place-archetype.js';
import type { PlaceArchetype } from '../src/types/place-scaffold.js';

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const featuresPath = path.join(pkgRoot, 'data', 'features.yml');
const rulesPath = path.join(pkgRoot, 'data', 'place-archetype-rules.yml');
const categoryDir = path.join(pkgRoot, 'data', 'category');
const generatedDir = path.join(pkgRoot, 'src', 'generated');
const configOutPath = path.join(generatedDir, 'place-archetype-config.ts');
const metaOutPath = path.join(generatedDir, 'geotype-layout-meta.ts');

type FeatureRow = {
  name?: string;
  category?: string;
  geometry_type?: string;
};

type ProfilesYaml = {
  archetype_defaults: PlaceArchetypeConfig['archetype_defaults'];
  slugs: PlaceArchetypeConfig['slugs'];
};

type CategoryRoot = { archetype?: string };

function loadArchetypeRulesYaml(): ProfilesYaml {
  const raw = yaml.load(fs.readFileSync(rulesPath, 'utf8')) as unknown;
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) {
    throw new Error('expected place-archetype-rules.yml object');
  }
  const obj = raw as Record<string, unknown>;
  if (!obj.archetype_defaults || typeof obj.archetype_defaults !== 'object') {
    throw new Error('place-archetype-rules.yml missing archetype_defaults');
  }
  if (!obj.slugs || typeof obj.slugs !== 'object') {
    throw new Error('place-archetype-rules.yml missing slugs');
  }
  return {
    archetype_defaults: obj.archetype_defaults as ProfilesYaml['archetype_defaults'],
    slugs: obj.slugs as ProfilesYaml['slugs'],
  };
}

function loadCategoryArchetypes(): Record<string, { archetype: PlaceArchetype }> {
  const out: Record<string, { archetype: PlaceArchetype }> = {};
  for (const file of fs.readdirSync(categoryDir).filter((f) => f.endsWith('.yml'))) {
    const data = yaml.load(fs.readFileSync(path.join(categoryDir, file), 'utf8')) as Record<
      string,
      CategoryRoot
    >;
    for (const [categoryKey, node] of Object.entries(data ?? {})) {
      if (!node?.archetype) continue;
      out[categoryKey] = {
        archetype: assertPlaceArchetype(node.archetype, `data/category/${file} → ${categoryKey}`),
      };
    }
  }
  return out;
}

function main(): void {
  const rules = loadArchetypeRulesYaml();
  const categories = loadCategoryArchetypes();

  const raw = yaml.load(fs.readFileSync(featuresPath, 'utf8')) as unknown;
  if (!Array.isArray(raw)) throw new Error('expected features.yml array');

  const metaBySlug: Record<string, { category: string; geometry_type: string }> = {};
  const categoriesUsed = new Set<string>();

  for (const row of raw as FeatureRow[]) {
    const slug = String(row.name ?? '').trim().toLowerCase();
    if (!slug) continue;
    const category = String(row.category ?? '').trim();
    const geometry_type = String(row.geometry_type ?? '').trim().toLowerCase();
    if (!category) {
      throw new Error(`features.yml "${slug}" missing category`);
    }
    if (!geometry_type) {
      throw new Error(`features.yml "${slug}" missing geometry_type`);
    }
    categoriesUsed.add(category);
    if (!categories[category]) {
      throw new Error(
        `missing category archetype for "${category}" (set archetype on data/category/${category}.yml root)`,
      );
    }
    metaBySlug[slug] = { category, geometry_type };
  }

  for (const category of categoriesUsed) {
    if (!categories[category]) {
      throw new Error(`features category "${category}" has no archetype in data/category/*.yml`);
    }
  }

  const config: PlaceArchetypeConfig = {
    archetype_defaults: rules.archetype_defaults,
    categories,
    slugs: rules.slugs,
  };

  fs.mkdirSync(generatedDir, { recursive: true });

  const configBody = `/** Generated by scripts/sync-place-archetypes.ts — do not edit. */

import type { PlaceArchetypeConfig } from '../resolve-place-archetype.js';

export const PLACE_ARCHETYPE_CONFIG = ${JSON.stringify(config, null, 2)} as const satisfies PlaceArchetypeConfig;
`;

  const metaBody = `/** Generated by scripts/sync-place-archetypes.ts — do not edit. */

import type { GeotypeLayoutMeta } from '../resolve-place-archetype.js';

export const GEOTYPE_LAYOUT_META_BY_SLUG = {
${Object.keys(metaBySlug)
  .sort()
  .map((slug) => `  '${slug}': ${JSON.stringify(metaBySlug[slug])},`)
  .join('\n')}
} as const satisfies Record<string, GeotypeLayoutMeta>;

export type GeneratedGeotypeLayoutSlug = keyof typeof GEOTYPE_LAYOUT_META_BY_SLUG;
`;

  fs.writeFileSync(configOutPath, configBody);
  fs.writeFileSync(metaOutPath, metaBody);

  console.log(
    `synced place archetypes → ${configOutPath}, ${metaOutPath} (${Object.keys(metaBySlug).length} slugs, ${Object.keys(categories).length} categories)`,
  );
}

main();
