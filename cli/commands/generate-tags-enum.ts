#!/usr/bin/env ts-node
import * as yaml from 'js-yaml';
import * as fs from 'fs';
import * as path from 'path';

interface Feature {
  id: string;
  name: string;
  tags: string;
}

interface SubCategory {
  id: string;
  name: string;
}

interface Category {
  name: string;
  id: string;
  subcategories: Record<string, SubCategory>;
}

function toEnumName(tag: string): string {
  // Prepends "TAG_" to avoid starting with a number, converts to uppercase, and replaces invalid chars
  return `TAG_${tag.toUpperCase().replace(/[^A-Z0-9_]/g, '_')}`;
}

export function generateTagsEnum(): string {
  const allCodes = new Set<string>();

  // 1. Read from data/features.yml
  const featuresPath = path.join(process.cwd(), 'data', 'features.yml');
  if (fs.existsSync(featuresPath)) {
    const featuresFile = fs.readFileSync(featuresPath, 'utf8');
    const featuresData = yaml.load(featuresFile) as Feature[];

    featuresData.forEach((feature) => {
      if (feature.tags) {
        feature.tags
          .split(',')
          .map((t) => t.trim())
          .filter((t) => t)
          .forEach((tag) => allCodes.add(tag));
      }
    });
  }

  // 2. Read from data/category/ directory
  const categoryDir = path.join(process.cwd(), 'data', 'category');
  if (fs.existsSync(categoryDir)) {
    const categoryFiles = fs.readdirSync(categoryDir).filter((f) => f.endsWith('.yml'));

    categoryFiles.forEach((file) => {
      const categoryKey = path.basename(file, '.yml');
      allCodes.add(categoryKey);

      const filePath = path.join(categoryDir, file);
      const fileContents = fs.readFileSync(filePath, 'utf8');
      const data = yaml.load(fileContents) as Record<string, Category>;

      const categoryData = data[categoryKey];
      if (categoryData && categoryData.subcategories) {
        Object.keys(categoryData.subcategories).forEach((subCategoryKey) => {
          allCodes.add(subCategoryKey);
        });
      }
    });
  }

  // 3. Generate the Enum
  let output = '// Automatically generated by `generate-tags-enum` command. Do not edit.\n\n';
  output += 'syntax = "proto3";\n\n';
  output += 'package geospatial;\n\n';
  output += 'enum TagCode {\n';
  output += '  TAG_CODE_UNSPECIFIED = 0;\n';

  let i = 1;
  Array.from(allCodes)
    .sort()
    .forEach((tag) => {
      output += `  ${toEnumName(tag)} = ${i++};\n`;
    });

  output += '}\n';
  
  return output;
} 